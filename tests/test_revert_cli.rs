    fs::create_dir_all(project_root).unwrap();
    fs::create_dir_all(project_root.join(".agents")).unwrap();
    let source_dir = project_root.join("docs/deep");
    fs::create_dir_all(&source_dir).unwrap();
    fs::write(source_dir.join("guide.md"), "# managed\n").unwrap();
    fs::write(
        project_root.join(".agents/agentsync.toml"),
        "source_dir = \".\"\n\n[agents.claude]\nenabled = true\n\n[agents.claude.targets.docs]\nsource = \"docs\"\ndestination = \"linked/{relative_path}/{file_name}\"\ntype = \"nested-glob\"\npattern = \"**/*.md\"\n",
    )
    .unwrap();

    let apply = run_agentsync(project_root, &["apply"]);
    assert!(
        apply.status.success(),
        "{}",
        String::from_utf8_lossy(&apply.stderr)
    );
    let destination = project_root.join("linked/deep/guide.md");
    assert!(
        destination.is_symlink(),
        "expected nested-glob link at {}\nstdout:\n{}\nstderr:\n{}",
        destination.display(),
        String::from_utf8_lossy(&apply.stdout),
        String::from_utf8_lossy(&apply.stderr)
    );
    let gitignore = fs::read_to_string(project_root.join(".gitignore")).unwrap();
    assert!(gitignore.contains("# START"));

    fs::remove_dir_all(project_root.join("docs")).unwrap();
    let revert = run_agentsync(project_root, &["revert"]);
    assert!(
        revert.status.success(),
        "{}",
        String::from_utf8_lossy(&revert.stderr)
    );
    assert!(
        destination.is_symlink(),
        "unknown nested-glob orphan is not inferred"
    );
    assert!(
        fs::read_to_string(project_root.join(".gitignore"))
            .unwrap()
            .contains("# START"),
        "incomplete revert must preserve the managed gitignore block"
    );
    let output = String::from_utf8_lossy(&revert.stdout);
    assert!(
        output.contains("Skipped: 1") || output.contains("skipped"),
        "{output}"
    );
