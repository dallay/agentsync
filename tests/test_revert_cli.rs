use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use sha2::{Digest, Sha256};
use tempfile::TempDir;

#[cfg(unix)]
fn agentsync_bin() -> &'static str {
    env!("CARGO_BIN_EXE_agentsync")
}

#[cfg(unix)]
fn run_agentsync(project_root: &Path, args: &[&str]) -> Output {
    let data_root = project_root.parent().unwrap().join(".local-data");
    run_agentsync_with_data_root(project_root, args, &data_root)
}

#[cfg(unix)]
fn run_agentsync_with_data_root(project_root: &Path, args: &[&str], data_root: &Path) -> Output {
    Command::new(agentsync_bin())
        .current_dir(project_root)
        .env("AGENTSYNC_DATA_DIR", data_root)
        .args(args)
        .output()
        .unwrap_or_else(|error| panic!("failed to run agentsync {:?}: {error}", args))
}

#[cfg(unix)]
fn ownership_manifest(project_root: &Path) -> PathBuf {
    let data_root = project_root.parent().unwrap().join(".local-data");
    ownership_manifest_at_data_root(&data_root)
}

#[cfg(unix)]
fn ownership_manifest_at_data_root(data_root: &Path) -> PathBuf {
    let ownership_root = data_root.join("agentsync/mcp-ownership");
    fs::read_dir(&ownership_root)
        .unwrap()
        .next()
        .unwrap()
        .unwrap()
        .path()
        .join("ownership.json")
}

