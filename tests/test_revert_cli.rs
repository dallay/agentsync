#[test]
#[cfg(unix)]
fn test_reapply_rejects_foreign_mcp_content_without_changing_config_or_journal() {
    let temp_dir = TempDir::new().unwrap();
    let project_root = &temp_dir.path().join("project");
    fs::create_dir_all(project_root).unwrap();
    write_mcp_fixture(project_root);
    let config_path = project_root.join(".mcp.json");
    let original = fs::read(&config_path).unwrap();

    let first_apply = run_agentsync(project_root, &["apply"]);
    assert!(
        first_apply.status.success(),
        "{}",
        String::from_utf8_lossy(&first_apply.stderr)
    );
    let applied = fs::read(&config_path).unwrap();
    let manifest_path = ownership_manifest(project_root);
    let manifest_before = fs::read(&manifest_path).unwrap();
    let manifest: serde_json::Value = serde_json::from_slice(&manifest_before).unwrap();
    let record = manifest["configs"]
        .as_object()
        .unwrap()
        .values()
        .next()
        .unwrap();
    let hash = |bytes: &[u8]| {
        Sha256::digest(bytes)
            .iter()
            .map(|byte| format!("{byte:02x}"))
            .collect::<String>()
    };
    assert_eq!(
        record["original_content"],
        String::from_utf8(original.clone()).unwrap()
    );
    assert_eq!(record["pre_write_sha256"], hash(&original));
    assert_eq!(record["applied_sha256"], hash(&applied));

    let foreign = br#"{"mcpServers":{"foreign":{"command":"foreign-tool"}}}"#;
    fs::write(&config_path, foreign).unwrap();
    let second_apply = run_agentsync(project_root, &["apply"]);

    assert!(
        !second_apply.status.success(),
        "apply must fail closed when the live MCP config matches neither ownership hash\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&second_apply.stdout),
        String::from_utf8_lossy(&second_apply.stderr)
    );
    assert_eq!(fs::read(&config_path).unwrap(), foreign);
    assert_eq!(fs::read(&manifest_path).unwrap(), manifest_before);
}

